function stripVietnameseDiacritics(input: string): string {
  return (input || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd')
    .replace(/Đ/g, 'D')
    .toLowerCase()
    .replace(/^(tinh|thanh pho|tp\.?|quan|huyen|thi xa|tx\.?)\s+/i, '')
    .trim();
}

export function findProvinceByName(provinceName: string): VietnamProvinceLocation | undefined {
  const target = stripVietnameseDiacritics(provinceName);
  if (!target) return undefined;
  return VIETNAM_PROVINCES.find((p) => {
    if (stripVietnameseDiacritics(p.name) === target) return true;
    if (stripVietnameseDiacritics(p.nameEn) === target) return true;
    return (p.aliases || []).some((a) => stripVietnameseDiacritics(a) === target);
  });
}

export function getDistrictsForProvince(provinceName: string): VietnamDistrictLocation[] {
  const prov = findProvinceByName(provinceName);
  return prov ? prov.districts : [];
}

export function findDistrictInProvince(
  provinceName: string,
  districtName: string
): VietnamDistrictLocation | undefined {
  const prov = findProvinceByName(provinceName);
  if (!prov) return undefined;
  const target = stripVietnameseDiacritics(districtName);
  if (!target) return undefined;
  return prov.districts.find(
    (d) =>
      stripVietnameseDiacritics(d.name) === target ||
      stripVietnameseDiacritics(d.nameEn) === target
  );
}

export function getLocalizedAdminName(
  name: string,
  lang: AppLanguage = 'vi',
  provinceContext?: string
): string {
  if (lang !== 'en') return name;
  const prov = findProvinceByName(name);
  if (prov) return prov.nameEn;
  if (provinceContext) {
    const dist = findDistrictInProvince(provinceContext, name);
    if (dist) return dist.nameEn;
  }
  return name;
}

function haversineKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

export function findNearestAdminLocation(lat: number, lon: number): {
  province: VietnamProvinceLocation;
  district: VietnamDistrictLocation;
  distanceKm: number;
} {
  let bestProv = VIETNAM_PROVINCES[0];
  let bestDist = VIETNAM_PROVINCES[0].districts[0];
  let minDistance = Infinity;

  for (const prov of VIETNAM_PROVINCES) {
    for (const dist of prov.districts) {
      const d = haversineKm(lat, lon, dist.lat, dist.lon);
      if (d < minDistance) {
        minDistance = d;
        bestProv = prov;
        bestDist = dist;
      }
    }
  }

  return {
    province: bestProv,
    district: bestDist,
    distanceKm: Number(minDistance.toFixed(1)),
  };
}
